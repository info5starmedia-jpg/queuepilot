<#
.SYNOPSIS
  QueuePilot engine packager (P5.5) — turns a locally built engine directory
  into a shareable, self-installing zip for family & friends.

.DESCRIPTION
  Takes a Chromium/Fury-core build output directory (the one containing
  chrome.exe), and produces:

    queuepilot-engine-<Version>-windows-x64.zip
      ├─ setup.ps1        (run this on the target machine)
      └─ payload.zip      (the engine files)

  setup.ps1 drops the engine under
    %LOCALAPPDATA%\QueuePilot\engines\fury-core\<Version>\windows-x64\
  and writes the install.json receipt the API's EngineHealthService scans,
  so the console sees the engine as a verified install with no download.

  The package is UNSIGNED — Windows SmartScreen and antivirus will flag it.
  setup.ps1 prints the exact AV-exclusion note at the end; docs/av-notes.md
  has the per-product steps. This is expected and normal for a self-built
  browser; see docs/av-notes.md before sharing.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\package-installer.ps1 `
    -EngineDir C:\qe\src\out\w64f3 -Version 1.0.0-qp.1
#>
[CmdletBinding()]
param(
  [Parameter(Mandatory = $true)]
  [string]$EngineDir,

  [Parameter(Mandatory = $true)]
  [string]$Version,

  [string]$OutDir = (Join-Path $PSScriptRoot "dist")
)

$ErrorActionPreference = "Stop"

$engine = (Resolve-Path $EngineDir).Path
if (-not (Test-Path (Join-Path $engine "chrome.exe"))) {
  throw "chrome.exe not found in $engine — pass the build output dir (e.g. C:\qe\src\out\w64f3)"
}

New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
$stage = Join-Path $OutDir "stage-$Version"
if (Test-Path $stage) { Remove-Item -Recurse -Force $stage }
New-Item -ItemType Directory -Force -Path $stage | Out-Null

# 1) payload.zip — the raw engine tree.
$payload = Join-Path $stage "payload.zip"
Write-Host "Packing $engine ..."
Compress-Archive -Path (Join-Path $engine "*") -DestinationPath $payload -CompressionLevel Optimal

# 2) Hash the payload bytes; setup.ps1 verifies before extracting and writes
#    the same digest into install.json (mirrors EngineInstaller's contract:
#    the pinned hash covers the archive bytes).
$sha256 = (Get-FileHash -Algorithm SHA256 $payload).Hash.ToLowerInvariant()
$installedAt = (Get-Date).ToUniversalTime().ToString("o")

# 3) Emit setup.ps1 with the hash + version baked in.
$setup = @"
# QueuePilot engine setup (generated by package-installer.ps1 — do not edit)
`$ErrorActionPreference = "Stop"
`$version  = "$Version"
`$expected = "$sha256"

`$here    = Split-Path -Parent `$MyInvocation.MyCommand.Path
`$payload = Join-Path `$here "payload.zip"
if (-not (Test-Path `$payload)) { throw "payload.zip missing next to setup.ps1" }

`$actual = (Get-FileHash -Algorithm SHA256 `$payload).Hash.ToLowerInvariant()
if (`$actual -ne `$expected) {
  throw "payload.zip checksum mismatch (expected `$expected, got `$actual) — do not install"
}

`$dest = Join-Path `$env:LOCALAPPDATA "QueuePilot\engines\fury-core\`$version\windows-x64"
Write-Host "Installing QueuePilot engine `$version to `$dest ..."
if (Test-Path `$dest) { Remove-Item -Recurse -Force `$dest }
New-Item -ItemType Directory -Force -Path `$dest | Out-Null
Expand-Archive -Path `$payload -DestinationPath `$dest

`$receipt = [ordered]@{
  kind        = "fury-core"
  version     = `$version
  platform    = "windows-x64"
  sha256      = `$expected
  url         = "file://local-package"
  installedAt = "$installedAt"
  dir         = `$dest
  binaryPath  = "chrome.exe"
}
`$receipt | ConvertTo-Json | Set-Content -Encoding UTF8 (Join-Path `$dest "install.json")

Write-Host ""
Write-Host "Done. Engine installed and receipt written." -ForegroundColor Green
Write-Host ""
Write-Host "IMPORTANT — antivirus:" -ForegroundColor Yellow
Write-Host "This engine is self-built and unsigned. SmartScreen or your AV may"
Write-Host "quarantine chrome.exe. If the browser fails to launch, add an exclusion"
Write-Host "for:  `$dest"
Write-Host "Steps per product: see docs/av-notes.md in the QueuePilot repo."
"@
Set-Content -Encoding UTF8 -Path (Join-Path $stage "setup.ps1") -Value $setup

# 4) Final zip.
$package = Join-Path $OutDir "queuepilot-engine-$Version-windows-x64.zip"
if (Test-Path $package) { Remove-Item -Force $package }
Compress-Archive -Path (Join-Path $stage "*") -DestinationPath $package -CompressionLevel Optimal
Remove-Item -Recurse -Force $stage

Write-Host ""
Write-Host "Package ready: $package" -ForegroundColor Green
Write-Host "sha256(payload): $sha256"
Write-Host "Share the zip; on the target machine: unzip, then run setup.ps1."
